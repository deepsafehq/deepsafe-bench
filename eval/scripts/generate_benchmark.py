#!/usr/bin/env python3
"""Regenerate BENCHMARK.md from the stored prediction matrix.

Reads ``eval/results/predictions_medium.csv.gz`` and writes ``BENCHMARK.md``.
Deliberately dependency-free (no numpy, pandas, or sklearn) so the published
numbers can be reproduced on a bare Python install.

Usage:
    python eval/scripts/generate_benchmark.py
"""

import collections
import csv
import gzip
import pathlib

PREDICTIONS = pathlib.Path("eval/results/predictions_medium.csv.gz")
OUTPUT = pathlib.Path("BENCHMARK.md")

# Provenance services answer "is there a watermark or manifest here", not
# "is this fake".  Scoring them as detectors over the whole set is meaningless,
# so they are reported separately rather than ranked.
PROVENANCE = {"c2pa", "sdxl_watermark", "audioseal", "videoseal", "trustmark"}

MODALITY_LABEL = {"images": "Image", "audio": "Audio", "video": "Video"}


def roc_auc(pairs):
    """Return ROC-AUC via the Mann-Whitney U statistic, with tie correction.

    Args:
        pairs: Iterable of ``(score, is_positive)`` tuples.

    Returns:
        The AUC as a float, or None if either class is empty.
    """
    pairs = [(s, y) for s, y in pairs if s is not None]
    positives = sum(1 for _, y in pairs if y)
    negatives = len(pairs) - positives
    if not positives or not negatives:
        return None
    order = sorted(pairs, key=lambda t: t[0])
    ranks = {}
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and order[j + 1][0] == order[i][0]:
            j += 1
        shared = (i + j) / 2 + 1
        for k in range(i, j + 1):
            ranks[k] = shared
        i = j + 1
    rank_sum = sum(ranks[k] for k, (_, y) in enumerate(order) if y)
    return (rank_sum - positives * (positives + 1) / 2) / (positives * negatives)


def as_float(row, column):
    """Return row[column] as a float, or None when absent or unparsable."""
    try:
        return float(row.get(column, ""))
    except (TypeError, ValueError):
        return None


def main():
    with gzip.open(PREDICTIONS, "rt") as handle:
        rows = list(csv.DictReader(handle))

    score_columns = sorted(c for c in rows[0] if c.startswith("prob_"))

    detectors, provenance = [], []
    for column in score_columns:
        name = column[len("prob_"):]
        scored = [r for r in rows if as_float(r, column) is not None]
        if not scored:
            continue
        modality = collections.Counter(r["modality"] for r in scored).most_common(1)[0][0]
        auc = roc_auc([(as_float(r, column), r["label"] == "fake") for r in scored])
        if auc is None:
            continue
        record = (name, modality, len(scored), auc)
        (provenance if name in PROVENANCE else detectors).append(record)

    detectors.sort(key=lambda t: (t[1], -t[3]))

    ensembles = {}
    for modality in ("images", "audio", "video"):
        subset = [
            r for r in rows
            if r["modality"] == modality and as_float(r, "ensemble_score") is not None
        ]
        ensembles[modality] = (
            len(subset),
            roc_auc([(as_float(r, "ensemble_score"), r["label"] == "fake") for r in subset]),
        )

    by_generator = collections.defaultdict(list)
    for row in rows:
        if row["label"] != "fake" or not row.get("ensemble_verdict"):
            continue
        caught = row["ensemble_verdict"].lower() == "fake"
        by_generator[(row["modality"], row["generator"])].append(caught)

    ranked = sorted(
        ((m, g, sum(v) / len(v), len(v)) for (m, g), v in by_generator.items() if len(v) >= 30),
        key=lambda t: t[2],
    )

    all_fakes = [v for values in by_generator.values() for v in values]
    recall = sum(all_fakes) / len(all_fakes)
    reals = [r for r in rows if r["label"] == "real" and r.get("ensemble_verdict")]
    false_positives = sum(1 for r in reals if r["ensemble_verdict"].lower() == "fake")
    fpr = false_positives / len(reals)

    out = []
    w = out.append
    w("# Benchmark Results\n")
    w("Generated by `eval/scripts/generate_benchmark.py` from")
    w("`eval/results/predictions_medium.csv.gz`. Every number below is")
    w(f"reproducible from that file: {len(rows):,} samples, "
      f"{len({r['generator'] for r in rows}):,} generators.\n")
    w("## Headline\n")
    w(f"- **Overall recall on fakes: {recall * 100:.1f}%**")
    w(f"- **False positive rate on real media: {fpr * 100:.1f}%**\n")
    w("Read that as: roughly a third of fake media passes undetected, and about")
    w("one in fifteen genuine files is wrongly flagged. This is the honest")
    w("operating point of an ensemble of 19 published detectors.\n")
    w("## Where it fails\n")
    w("Detection rate by generator, worst first. The pattern is not subtle:")
    w("detectors catch the 2022-2023 diffusion models they were trained on and")
    w("miss modern video generators almost entirely.\n")
    w("| Generator | Modality | Caught | n |")
    w("|---|---|---|---|")
    for modality, generator, rate, n in ranked[:15]:
        w(f"| {generator} | {MODALITY_LABEL.get(modality, modality)} | "
          f"**{rate * 100:.1f}%** | {n} |")
    w("")
    w("And where it succeeds, for contrast:\n")
    w("| Generator | Modality | Caught | n |")
    w("|---|---|---|---|")
    for modality, generator, rate, n in reversed(ranked[-8:]):
        w(f"| {generator} | {MODALITY_LABEL.get(modality, modality)} | "
          f"{rate * 100:.1f}% | {n} |")
    w("")
    w("## Ensemble AUC by modality\n")
    w("| Modality | Samples | AUC |")
    w("|---|---|---|")
    for modality, (n, auc) in ensembles.items():
        w(f"| {MODALITY_LABEL[modality]} | {n:,} | {auc:.4f} |")
    w("")
    w("These are **held-out evaluation** figures. They are lower than the")
    w("cross-validated figures produced during meta-learner training, and the")
    w("gap is the point: cross-validated scores on the training distribution")
    w("overstate what a detector does in the wild.\n")
    w("## Individual models\n")
    w("| Model | Modality | Samples | AUC |")
    w("|---|---|---|---|")
    for name, modality, n, auc in detectors:
        w(f"| {name} | {MODALITY_LABEL.get(modality, modality)} | {n:,} | {auc:.4f} |")
    w("")
    w("The most uncomfortable line in that table is **npr_video**, an image")
    w("detector applied frame by frame, which outscores every purpose-built")
    w("video model in the lineup.\n")
    w("## Provenance services\n")
    w("These answer *is there a watermark or manifest here*, not *is this fake*.")
    w("AUC over the full set is the wrong metric for them and is shown only to")
    w("make clear why they are excluded from the ranking above: a watermark")
    w("detector scores near chance on media that carries no watermark.\n")
    w("| Service | Samples | AUC |")
    w("|---|---|---|")
    for name, _modality, n, auc in sorted(provenance):
        w(f"| {name} | {n:,} | {auc:.4f} |")
    w("")
    w("When a signal *is* present, provenance is far stronger evidence than any")
    w("detector score. A C2PA manifest is a fact; a model score is an estimate.\n")
    w("## Caveats\n")
    w("- One evaluation run (2026-04-10). Not averaged over seeds.")
    w("- TrustMark was added after this run and is absent.")
    w("- The manifest carries no `language` field, so no per-language breakdown")
    w("  is reported. Do not infer multilingual performance from these numbers.")
    w("- Thresholds are the ensemble's own defaults, not tuned per generator.")

    OUTPUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUTPUT} ({len(out)} lines)")


if __name__ == "__main__":
    main()
